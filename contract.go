package main

import (
	"bytes"
	_ "embed"
	"fmt"
	"os"
	"path/filepath"

	"github.com/yoheimuta/go-protoparser/v4"
	"github.com/yoheimuta/go-protoparser/v4/parser"

	v0 "github.com/codefly-dev/core/generated/go/codefly/base/v0"
	"github.com/codefly-dev/core/standards"
	"github.com/codefly-dev/core/wool"
)

// storageSource is the gateway's gRPC API, the codefly/storage/v0 proto the
// gateway binary is built from.
//
//go:embed proto/codefly/storage/v0/storage.proto
var storageSource []byte

const contractHeader = `// Code generated by codefly.dev/object-storage. DO NOT EDIT.
//
// The object-storage gateway's API (codefly.storage.v0), published here so
// services that depend on this one can generate a client. ` + "`codefly sync`" + `
// rewrites this file from the agent.

`

// storageContract is the file published into an object-storage service at
// standards.DependencyProtoPath: the storage API under a generated-file header.
var storageContract = append([]byte(contractHeader), storageSource...)

// contractAPI is the gRPC API this agent advertises, parsed from the contract
// the way core's resources.LoadGrpcAPI parses a proto file. It is built from
// the embedded contract, not read from the service, so a dependent's
// `codefly sync` generates a full client even before this service has been
// synced once (a dependency is Loaded before it is Synced).
func contractAPI() (*v0.GrpcAPI, error) {
	got, err := protoparser.Parse(bytes.NewReader(storageContract))
	if err != nil {
		return nil, fmt.Errorf("cannot parse the storage API contract: %w", err)
	}
	api := &v0.GrpcAPI{Proto: storageContract}
	for _, element := range got.ProtoBody {
		switch element := element.(type) {
		case *parser.Package:
			api.Package = element.Name
		case *parser.Service:
			for _, inside := range element.ServiceBody {
				if rpc, ok := inside.(*parser.RPC); ok {
					api.Rpcs = append(api.Rpcs, &v0.RPC{Name: rpc.RPCName, ServiceName: element.ServiceName})
				}
			}
		}
	}
	return api, nil
}

func contractPath(serviceDir string) string {
	return filepath.Join(serviceDir, filepath.FromSlash(standards.DependencyProtoPath))
}

// contractCurrent reports whether the service already holds this agent's
// contract.
func contractCurrent(serviceDir string) (bool, error) {
	if serviceDir == "" {
		return false, fmt.Errorf("service directory is empty")
	}
	current, err := os.ReadFile(contractPath(serviceDir))
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("cannot read dependency contract: %w", err)
	}
	return bytes.Equal(current, storageContract), nil
}

// writeDependencyContract publishes the API this agent serves at the service's
// dependency contract path, where core's Service.LoadEndpoints and any tool
// reading the service directory find it. It rewrites the file only when its
// content differs, so a sync after an agent upgrade refreshes the contract and
// an unchanged one leaves it untouched.
func writeDependencyContract(serviceDir string) (bool, error) {
	current, err := contractCurrent(serviceDir)
	if err != nil || current {
		return false, err
	}
	path := contractPath(serviceDir)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, fmt.Errorf("cannot create dependency contract directory: %w", err)
	}
	if err := os.WriteFile(path, storageContract, 0o644); err != nil {
		return false, fmt.Errorf("cannot write dependency contract %s: %w", path, err)
	}
	return true, nil
}

// publishContract writes the contract into this service's directory.
func (s *Builder) publishContract() error {
	written, err := writeDependencyContract(s.Location)
	if err != nil {
		return err
	}
	if written {
		s.Wool.Info("published storage API contract", wool.Field("path", standards.DependencyProtoPath))
	}
	return nil
}

// advertiseContract makes endpoint carry the storage API, keeping whether it
// is secured.
func advertiseContract(endpoint *v0.Endpoint) error {
	api, err := contractAPI()
	if err != nil {
		return err
	}
	api.Secured = endpoint.GetApiDetails().GetGrpc().GetSecured()
	endpoint.ApiDetails = &v0.API{Value: &v0.API_Grpc{Grpc: api}}
	return nil
}

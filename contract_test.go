func TestPublishedContractIsTheStorageAPI(t *testing.T) {
	source, err := os.ReadFile(filepath.Join("proto", "codefly", "storage", "v0", "storage.proto"))
	require.NoError(t, err)
	require.True(t, bytes.HasSuffix(storageContract, source), "the published contract is the proto the gateway is built from")
	require.True(t, bytes.HasPrefix(storageContract, []byte("// Code generated by codefly.dev/object-storage. DO NOT EDIT.")))
}

// contractAPI must advertise exactly what core would read from the published
// file, so Load (in memory) and LoadEndpoints (from disk) agree.
func TestContractAPIMatchesCoreReadingThePublishedFile(t *testing.T) {
	dir := t.TempDir()
	_, err := writeDependencyContract(dir)
	require.NoError(t, err)
	fromDisk, err := resources.LoadGrpcAPI(context.Background(), shared.Pointer(contractPath(dir)))
	require.NoError(t, err)

	api, err := contractAPI()
	require.NoError(t, err)
	require.Equal(t, fromDisk.GetPackage(), api.GetPackage())
	require.Equal(t, fromDisk.GetProto(), api.GetProto())
	require.Len(t, api.GetRpcs(), len(fromDisk.GetRpcs()))
	for i, rpc := range fromDisk.GetRpcs() {
		require.Equal(t, rpc.GetName(), api.GetRpcs()[i].GetName())
		require.Equal(t, rpc.GetServiceName(), api.GetRpcs()[i].GetServiceName())
	}
	require.Equal(t, "codefly.storage.v0", api.GetPackage())
	names := map[string]bool{}
	for _, rpc := range api.GetRpcs() {
		names[rpc.GetName()] = true
	}
	for _, name := range []string{"Stat", "Get", "Put", "Delete", "List", "Presign", "Watch", "Capabilities", "Ready"} {
		require.True(t, names[name], "contract is missing rpc %s", name)
	}
}

func TestWriteDependencyContractLeavesACurrentContractUntouched(t *testing.T) {
	dir := t.TempDir()
	written, err := writeDependencyContract(dir)
	require.NoError(t, err)
	require.True(t, written)
	past := time.Now().Add(-time.Hour).Truncate(time.Second)
	require.NoError(t, os.Chtimes(contractPath(dir), past, past))

	written, err = writeDependencyContract(dir)
	require.NoError(t, err)
	require.False(t, written)
	info, err := os.Stat(contractPath(dir))
	require.NoError(t, err)
	require.True(t, info.ModTime().Equal(past), "an unchanged contract is not rewritten")
}

